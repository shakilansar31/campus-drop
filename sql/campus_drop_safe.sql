-- Safe Oracle XE setup for CampusDrop. Run inside XEPDB1 as SYSTEM or SYSDBA.
-- Creates missing objects only and inserts the five demo items only when absent.
SET SERVEROUTPUT ON

DECLARE
    object_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO object_count FROM dba_tables WHERE owner='SYSTEM' AND table_name='ITEMS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE SYSTEM.ITEMS (
            ITEM_ID NUMBER PRIMARY KEY,
            ITEM_NAME VARCHAR2(100) NOT NULL,
            CATEGORY VARCHAR2(50) NOT NULL,
            LOCATION VARCHAR2(100) NOT NULL,
            REPORT_DATE VARCHAR2(30) DEFAULT TO_CHAR(SYSDATE, 'DD/MM/YYYY'),
            REPORTED_BY VARCHAR2(100) NOT NULL,
            STUDENT_ID VARCHAR2(30),
            ITEM_TYPE VARCHAR2(10) CONSTRAINT CHK_ITEM_TYPE CHECK (ITEM_TYPE IN ('LOST', 'FOUND')),
            STATUS VARCHAR2(20) CONSTRAINT CHK_STATUS CHECK (STATUS IN ('ACTIVE', 'CLAIMED', 'RETURNED'))
        )~';
        DBMS_OUTPUT.PUT_LINE('Created SYSTEM.ITEMS');
    END IF;

    SELECT COUNT(*) INTO object_count FROM dba_tables WHERE owner='SYSTEM' AND table_name='CLAIMS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE SYSTEM.CLAIMS (
            CLAIM_ID NUMBER PRIMARY KEY,
            ITEM_ID NUMBER NOT NULL,
            STUDENT_NAME VARCHAR2(100) NOT NULL,
            STUDENT_ID VARCHAR2(30) NOT NULL,
            CLAIM_REASON VARCHAR2(500) NOT NULL,
            CLAIM_STATUS VARCHAR2(20) DEFAULT 'PENDING'
                CONSTRAINT CHK_CLAIM_STATUS CHECK (CLAIM_STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
            CLAIM_DATE VARCHAR2(30) DEFAULT TO_CHAR(SYSDATE, 'DD/MM/YYYY'),
            CONSTRAINT FK_CLAIMS_ITEM FOREIGN KEY (ITEM_ID)
                REFERENCES SYSTEM.ITEMS(ITEM_ID) ON DELETE CASCADE
        )~';
        DBMS_OUTPUT.PUT_LINE('Created SYSTEM.CLAIMS');
    END IF;

    SELECT COUNT(*) INTO object_count FROM dba_tables WHERE owner='SYSTEM' AND table_name='RECOVERY_HISTORY';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE SYSTEM.RECOVERY_HISTORY (
            HISTORY_ID NUMBER PRIMARY KEY,
            ITEM_ID NUMBER NOT NULL,
            ITEM_NAME VARCHAR2(100) NOT NULL,
            STUDENT_NAME VARCHAR2(100) NOT NULL,
            RETURN_DATE VARCHAR2(30) DEFAULT TO_CHAR(SYSDATE, 'DD/MM/YYYY'),
            STATUS VARCHAR2(20) DEFAULT 'RETURNED',
            CONSTRAINT FK_HISTORY_ITEM FOREIGN KEY (ITEM_ID)
                REFERENCES SYSTEM.ITEMS(ITEM_ID) ON DELETE CASCADE
        )~';
        DBMS_OUTPUT.PUT_LINE('Created SYSTEM.RECOVERY_HISTORY');
    END IF;

    SELECT COUNT(*) INTO object_count FROM dba_sequences WHERE sequence_owner='SYSTEM' AND sequence_name='ITEM_SEQ';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SYSTEM.ITEM_SEQ START WITH 106 INCREMENT BY 1 NOCACHE';
    END IF;
    SELECT COUNT(*) INTO object_count FROM dba_sequences WHERE sequence_owner='SYSTEM' AND sequence_name='CLAIM_SEQ';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SYSTEM.CLAIM_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
    END IF;
    SELECT COUNT(*) INTO object_count FROM dba_sequences WHERE sequence_owner='SYSTEM' AND sequence_name='HISTORY_SEQ';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SYSTEM.HISTORY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
    END IF;

    SELECT COUNT(*) INTO object_count FROM dba_indexes WHERE owner='SYSTEM' AND index_name='IDX_ITEMS_NAME';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX SYSTEM.IDX_ITEMS_NAME ON SYSTEM.ITEMS(LOWER(ITEM_NAME))';
    END IF;
    SELECT COUNT(*) INTO object_count FROM dba_indexes WHERE owner='SYSTEM' AND index_name='IDX_ITEMS_STATUS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX SYSTEM.IDX_ITEMS_STATUS ON SYSTEM.ITEMS(STATUS)';
    END IF;
    SELECT COUNT(*) INTO object_count FROM dba_indexes WHERE owner='SYSTEM' AND index_name='IDX_ITEMS_TYPE';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX SYSTEM.IDX_ITEMS_TYPE ON SYSTEM.ITEMS(ITEM_TYPE)';
    END IF;
END;
/

MERGE INTO SYSTEM.ITEMS dst
USING (
    SELECT 101 ITEM_ID, 'Black Wallet' ITEM_NAME, 'Personal' CATEGORY, 'Library' LOCATION,
           '25/09/2026' REPORT_DATE, 'Rahul Sharma' REPORTED_BY, '24CS010' STUDENT_ID,
           'LOST' ITEM_TYPE, 'ACTIVE' STATUS FROM DUAL
    UNION ALL SELECT 102, 'Casio Calculator', 'Electronics', 'Block B', '24/09/2026', 'Ananya Roy', '24EC045', 'FOUND', 'ACTIVE' FROM DUAL
    UNION ALL SELECT 103, 'Blue Water Bottle', 'Personal', 'Canteen', '25/09/2026', 'Vikram Singh', '24ME089', 'LOST', 'ACTIVE' FROM DUAL
    UNION ALL SELECT 104, 'HP Laptop Charger', 'Electronics', 'Lab 2', '23/09/2026', 'Neha Gupta', '24CS102', 'FOUND', 'ACTIVE' FROM DUAL
    UNION ALL SELECT 105, 'College ID Card', 'Documents', 'Main Block', '25/09/2026', 'Amit Verma', '24IT055', 'LOST', 'ACTIVE' FROM DUAL
) src
ON (dst.ITEM_ID = src.ITEM_ID)
WHEN NOT MATCHED THEN INSERT (
    ITEM_ID, ITEM_NAME, CATEGORY, LOCATION, REPORT_DATE, REPORTED_BY, STUDENT_ID, ITEM_TYPE, STATUS
) VALUES (
    src.ITEM_ID, src.ITEM_NAME, src.CATEGORY, src.LOCATION, src.REPORT_DATE,
    src.REPORTED_BY, src.STUDENT_ID, src.ITEM_TYPE, src.STATUS
);

COMMIT;
SELECT 'CAMPUS DROP SCHEMA READY IN XEPDB1' AS STATUS FROM DUAL;
